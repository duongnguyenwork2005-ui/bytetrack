"""Final read-only evidence validation and review manifest within R107."""
import ast
import datetime as dt
import hashlib
import json
from pathlib import Path
import sys

OUT = Path(__file__).resolve().parent
ROOT = OUT.parents[2]
def sha(path):
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()
def read(name):
    return json.loads((OUT / name).read_text(encoding="utf-8"))

frozen = read("inputs.json")
assert all(sha(Path(p)) == digest for p, digest in frozen["sha256"].items())
assert read("dev_gate.json")["gate_pass"] is False
assert read("verification.json")["complete_video_seed_units"] == 36
assert read("integrity_verified.json")["total_frames"] == 50757
checks = read("tier1_checks.json")
for stage in ("unit", "regression", "preflight", "smoke", "dev", "eval", "integrity", "verify"):
    latest = [r for r in checks if r["stage"] == stage][-1]
    assert latest["exit"] == 0 and latest["child_waited"], stage
assert [r["exit"] for r in checks if r["stage"] == "unit"] == [1, 1, 0]
plan = ROOT / "handoff/PLAN_DA_CHOT.md"
assert "**R107 — PF sau ghép lại" in plan.read_text(encoding="utf-8")[:5000]
assert plan.stat().st_mtime_ns <= (OUT / "10_ket_qua.md").stat().st_mtime_ns
for path in OUT.glob("*.py"):
    ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
files = sorted(p for p in OUT.rglob("*") if p.is_file() and p.name != "review_manifest.json")
manifest = {"created_utc": dt.datetime.now(dt.timezone.utc).isoformat(),
            "files_sha256": {str(p.relative_to(OUT)): sha(p) for p in files},
            "frozen_inputs_unchanged": len(frozen["sha256"]),
            "plan_updated_before_report_mtime_checked": True,
            "recorded_child_processes_waited": all(r["child_waited"] for r in checks),
            "independent_review": "Pending separate Codex session by orchestrator",
            "gate": "Rejected; no transfer run",
            "outside_write_paths_exception": "Ultralytics/settings.json generated by first unit import; retained with diagnostic hash"}
(OUT / "review_manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
print(f"FINAL CHECK exit0: {len(files)} review files hashed; 91 frozen inputs unchanged; completed checks; PLAN before report")
